const multiply = (a, b) => {
  return a * b;
};

const isEven = (num) => {
  return num % 2 == 0;
};

const getFullName = (firstname, lastname) => {
  return firstname + " " + lastname;
};

const moreThanTen = (num) => {
  return num > 10;
};

const nameAge = (names, ages) => {
  return names + " is " + ages + " years old.";
};
